def get_card_by_name(card_name: str) -> dict | None:
    for card in TAROT_DECK:
        if card["name"].lower() == card_name.strip().lower():
            return card
    return None


def get_sphere_meaning(card_name: str, sphere: str, fallback_meaning: str = "") -> str:
    card = get_card_by_name(card_name)
    if not card:
        return fallback_meaning
    spheres = card.get("spheres", {})
    return spheres.get(sphere) or spheres.get("Загальне") or card.get("meaning", fallback_meaning)